    [InlineData(-26 * 86_400, -1, RelativeTimeUnit.Month)]
    [InlineData(320 * 86_400, 1, RelativeTimeUnit.Year)]
    public void 单位的取法同vue的relativeUnit(int seconds, long value, RelativeTimeUnit unit) =>
        Assert.Equal((value, unit), RelativeTimeText.Of(TimeSpan.FromSeconds(seconds)));
