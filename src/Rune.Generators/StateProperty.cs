using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rune.Generators;

/// <summary>
/// 一个 [State] 属性生成实现所需的全部信息（只有字符串，按值比较，增量生成器才能缓存）。
/// </summary>
internal sealed record StateProperty(
    string HintName,
    string? Namespace,
    EquatableArray<string> ContainingTypes,
    string Modifiers,
    string Type,
    string Name,
    string StateAccessibility,
    string SetterAccessibility,
    string InitialValue)
{
    static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <summary>从属性声明读出生成所需的信息；写法不对时返回诊断。</summary>
    public static (StateProperty? Property, DiagnosticInfo? Error) From(GeneratorAttributeSyntaxContext context)
    {
        var symbol = (IPropertySymbol)context.TargetSymbol;
        var syntax = (PropertyDeclarationSyntax)context.TargetNode;
        var location = syntax.Identifier.GetLocation();

        if (symbol.IsStatic)
            return (null, DiagnosticInfo.Create(Diagnostics.StaticState, location, symbol.Name));
        if (symbol.GetMethod is null || symbol.SetMethod is null || symbol.SetMethod.IsInitOnly)
            return (null, DiagnosticInfo.Create(Diagnostics.NeedsGetAndSet, location, symbol.Name, symbol.Type.ToDisplayString()));

        var property = new StateProperty(
            HintName: HintNameOf(symbol),
            Namespace: symbol.ContainingType.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingType.ContainingNamespace.ToDisplayString(),
            ContainingTypes: new EquatableArray<string>(ContainingTypeDeclarations(symbol.ContainingType)),
            Modifiers: string.Join(" ", syntax.Modifiers.Select(m => m.Text)),
            Type: symbol.Type.ToDisplayString(TypeFormat),
            Name: symbol.Name,
            // 交出信号本身的属性：取 get 与 set 里更严格的那个，否则 private set 会被它绕过
            StateAccessibility: Keyword(Narrower(symbol.GetMethod.DeclaredAccessibility, symbol.SetMethod.DeclaredAccessibility)),
            SetterAccessibility: symbol.SetMethod.DeclaredAccessibility == symbol.DeclaredAccessibility ? "" : Keyword(symbol.SetMethod.DeclaredAccessibility) + " ",
            InitialValue: InitialValueOf(context) ?? "default!");
        return (property, null);
    }

    /// <summary>生成的源码。</summary>
    public string ToSource()
    {
        var field = $"__rune_{Name}";
        var members = new StringBuilder()
            .AppendLine($"private global::Rune.State<{Type}>? {field};")
            .AppendLine()
            .AppendLine($"/// <summary>{Name} 背后的状态：交给需要信号本身的地方（子组件参数、Bindable、跨组件共享）。</summary>")
            .AppendLine($"{StateAccessibility} global::Rune.State<{Type}> {Name}State => {field} ??= new({InitialValue});")
            .AppendLine()
            .AppendLine($"{Modifiers} {Type} {Name}")
            .AppendLine("{")
            .AppendLine($"    get => {Name}State.Value;")
            .AppendLine($"    {SetterAccessibility}set => {Name}State.Value = value;")
            .AppendLine("}")
            .ToString();

        // 从里到外套上包含类型的 partial 声明
        var body = members;
        foreach (var declaration in ContainingTypes.Reverse())
            body = $"{declaration}\n{{\n{Indent(body)}\n}}\n";

        var header = "// <auto-generated/>\n// 由 Rune.Generators 的 StateGenerator 生成：[State] 属性的实现。\n#nullable enable\n\n";
        return header + (Namespace is null ? "" : $"namespace {Namespace};\n\n") + body;
    }

    /// <summary>[State(5)]：直接取源码里的参数表达式，类型由 State&lt;T&gt; 的构造参数检查。</summary>
    static string? InitialValueOf(GeneratorAttributeSyntaxContext context) =>
        (context.Attributes[0].ApplicationSyntaxReference?.GetSyntax() as AttributeSyntax)
            ?.ArgumentList?.Arguments.FirstOrDefault()?.Expression.ToString();

    /// <summary>包含类型的声明，从外到内：<c>partial class Outer</c>、<c>partial record Inner&lt;T&gt;</c>。</summary>
    static string[] ContainingTypeDeclarations(INamedTypeSymbol type)
    {
        var declarations = new List<string>();
        for (var current = type; current is not null; current = current.ContainingType)
        {
            var kind = current switch
            {
                { IsRecord: true, IsValueType: true } => "record struct",
                { IsRecord: true } => "record",
                { IsValueType: true } => "struct",
                _ => "class",
            };
            var generics = current.TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", current.TypeParameters.Select(p => p.Name))}>";
            declarations.Insert(0, $"partial {kind} {current.Name}{generics}");
        }
        return [.. declarations];
    }

    static string HintNameOf(IPropertySymbol symbol) =>
        symbol.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", "").Replace('<', '[').Replace('>', ']')
        + "." + symbol.Name + ".State.g.cs";

    /// <summary>两个访问级别里更严格的；protected 与 internal 互不包含时取 private protected。</summary>
    static Accessibility Narrower(Accessibility a, Accessibility b)
    {
        if (a == b) return a;
        if (Includes(a, b)) return b;
        if (Includes(b, a)) return a;
        return Accessibility.ProtectedAndInternal;
    }

    /// <summary><paramref name="wider"/> 能访问的范围包含 <paramref name="narrower"/>。</summary>
    static bool Includes(Accessibility wider, Accessibility narrower) => (wider, narrower) switch
    {
        (Accessibility.Public, _) => true,
        (_, Accessibility.Private) => true,
        (Accessibility.ProtectedOrInternal, _) => true,
        (Accessibility.Protected or Accessibility.Internal, Accessibility.ProtectedAndInternal) => true,
        _ => false,
    };

    static string Keyword(Accessibility accessibility) => accessibility switch
    {
        Accessibility.Public => "public",
        Accessibility.Protected => "protected",
        Accessibility.Internal => "internal",
        Accessibility.ProtectedOrInternal => "protected internal",
        Accessibility.ProtectedAndInternal => "private protected",
        _ => "private",
    };

    static string Indent(string text) =>
        string.Join("\n", text.TrimEnd().Split('\n').Select(line => line.TrimEnd('\r')).Select(line => line.Length == 0 ? line : "    " + line));
}
