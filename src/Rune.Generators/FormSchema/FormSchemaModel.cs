using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rune.Generators;

/// <summary>一个 [FormSchema] 类型生成的源码与诊断（只有字符串，按值比较，增量生成器才能缓存）。</summary>
internal sealed record FormSchemaModel(string HintName, string? Source, EquatableArray<DiagnosticInfo> Diagnostics)
{
    const string Ui = "global::Rune.UI.";

    static readonly SymbolDisplayFormat typeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <summary>读出类型的字段并生成源码；写法不对的属性跳过并报诊断。</summary>
    public static FormSchemaModel From(GeneratorAttributeSyntaxContext context, CancellationToken cancellation)
    {
        var type = (INamedTypeSymbol)context.TargetSymbol;
        var syntax = (TypeDeclarationSyntax)context.TargetNode;
        var diagnostics = new List<DiagnosticInfo>();
        var hintName = type.ToDisplayString(typeFormat).Replace("global::", "").Replace('<', '[').Replace('>', ']') + ".FormSchema.g.cs";

        if (!IsPartialChain(type, cancellation) || type.IsStatic || type.IsGenericType || type.IsValueType)
        {
            diagnostics.Add(DiagnosticInfo.Create(Generators.Diagnostics.FormSchemaType, syntax.Identifier.GetLocation(), type.Name));
            return new(hintName, null, new([.. diagnostics]));
        }

        var compilation = context.SemanticModel.Compilation;
        var hasDates = compilation.GetTypeByMetadataName("Rune.UI.SchemaDateControls") is not null;
        var self = type.ToDisplayString(typeFormat);
        var fields = new List<(int Order, int Index, string Code)>();
        var index = 0;
        foreach (var property in PropertiesOf(type))
        {
            cancellation.ThrowIfCancellationRequested();
            var field = FieldOf(type, self, property, hasDates, diagnostics);
            if (field is not null) fields.Add((OrderOf(property), index++, field));
        }

        var list = $"global::System.Collections.Generic.IReadOnlyList<{Ui}SchemaField<{self}>>";
        var body = new StringBuilder()
            .AppendLine($"{DeclarationOf(type)} : {Ui}IFormSchema<{self}>")
            .AppendLine("{")
            .AppendLine($"    private static {list} __runeFormSchemaFields;")
            .AppendLine()
            .AppendLine($"    static {list} {Ui}IFormSchema<{self}>.FormSchemaFields => __runeFormSchemaFields ??= new {Ui}SchemaField<{self}>[]")
            .AppendLine("    {");
        // [Display(Order)] 写了的按它排，没写的保持声明的顺序（同 DataAnnotations 的约定：没写的排在写了的后面）
        foreach (var field in fields.OrderBy(f => f.Order).ThenBy(f => f.Index))
            body.AppendLine($"        {field.Code},");
        body.AppendLine("    };").AppendLine("}");

        var code = body.ToString();
        for (var container = type.ContainingType; container is not null; container = container.ContainingType)
            code = $"{DeclarationOf(container)}\n{{\n{Indent(code)}\n}}\n";
        var header = "// <auto-generated/>\n// 由 Rune.Generators 的 FormSchemaGenerator 生成：[FormSchema] 的字段描述。\n#nullable disable\n\n";
        var ns = type.ContainingNamespace.IsGlobalNamespace ? "" : $"namespace {type.ContainingNamespace.ToDisplayString()};\n\n";
        return new(hintName, header + ns + code, new([.. diagnostics]));
    }

    /// <summary>生成字段的属性：公开的实例属性，基类的在前；[ScaffoldColumn(false)] 的不要。</summary>
    static IEnumerable<IPropertySymbol> PropertiesOf(INamedTypeSymbol type)
    {
        var chain = new List<INamedTypeSymbol>();
        for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType) chain.Insert(0, current);
        foreach (var current in chain)
            foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
            {
                if (property.IsStatic || property.IsIndexer || property.DeclaredAccessibility != Accessibility.Public || property.GetMethod is null) continue;
                if (Attribute(property, "System.ComponentModel.DataAnnotations.ScaffoldColumnAttribute") is { } scaffold
                    && scaffold.ConstructorArguments.FirstOrDefault().Value is false) continue;
                // 记录的 EqualityContract 之类编译器生成的属性
                if (property.IsImplicitlyDeclared) continue;
                yield return property;
            }
    }

    static int OrderOf(IPropertySymbol property) =>
        Named(Attribute(property, "System.ComponentModel.DataAnnotations.DisplayAttribute"), "Order") is int order ? order : 10000;

    /// <summary>一个字段的构造代码；生成不了时报诊断并返回 null。</summary>
    static string? FieldOf(INamedTypeSymbol owner, string self, IPropertySymbol property, bool hasDates, List<DiagnosticInfo> diagnostics)
    {
        var location = property.Locations.FirstOrDefault() ?? Location.None;
        var display = Attribute(property, "System.ComponentModel.DataAnnotations.DisplayAttribute");
        var formField = Attribute(property, "Rune.UI.FormFieldAttribute");
        var asked = Named(formField, "Control") is int control ? control : 0;
        var name = property.Name;
        var settable = property.SetMethod is { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false };

        // 控件：嵌套对象、对象列表、值字段
        var type = property.Type;
        string kind;
        string controlName;
        string? renderer = null;
        string? itemType = null;
        IReadOnlyList<(string Value, string Label)> options = [];
        if (HasFormSchema(type))
        {
            kind = "Object";
            controlName = "Object";
        }
        else if (ListItemOf(type) is { } item && HasFormSchema(item))
        {
            kind = "List";
            controlName = asked == (int)Control.Table ? "Table" : "List";
            itemType = item.ToDisplayString(typeFormat);
            if (item.IsAbstract || !((INamedTypeSymbol)item).InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public))
            {
                diagnostics.Add(DiagnosticInfo.Create(Generators.Diagnostics.FormSchemaProperty, location, name, $"列表的元素 {item.Name} 要有公开的无参构造函数（加一行时新建）"));
                return null;
            }
        }
        else
        {
            kind = "Value";
            // 只读的属性（算出来的值、条件用的 bool）不是字段
            if (!settable) return null;
            var picked = ControlOf(property, type, asked, hasDates, out options);
            if (picked.Error is { } error)
            {
                diagnostics.Add(DiagnosticInfo.Create(Generators.Diagnostics.FormSchemaProperty, location, name, error));
                return null;
            }
            (controlName, renderer) = (picked.Control!, picked.Renderer!);
        }

        var info = new StringBuilder($"new {Ui}SchemaFieldInfo({Literal(name)}, {Literal(Named(display, "Name") as string ?? name)}, {Ui}SchemaControl.{controlName})");
        var inits = new List<string>();
        void Init(string member, object? value)
        {
            switch (value)
            {
                case string text when text.Length > 0: inits.Add($"{member} = {Literal(text)}"); break;
                case int number when number > 0: inits.Add($"{member} = {number.ToString(CultureInfo.InvariantCulture)}"); break;
                case true: inits.Add($"{member} = true"); break;
            }
        }
        Init("Description", Named(display, "Description"));
        Init("Placeholder", Named(display, "Prompt"));
        Init("Group", Named(display, "GroupName"));
        Init("Tab", Named(formField, "Tab"));
        Init("Unit", Named(formField, "Unit"));
        Init("Span", Named(formField, "Span"));
        Init("FullRow", Named(formField, "FullRow"));
        Init("Required", Attribute(property, "System.ComponentModel.DataAnnotations.RequiredAttribute") is not null);
        Init("Source", Named(formField, "Source"));
        Init("Sum", Named(formField, "Sum"));
        if (options.Count > 0)
            inits.Add($"Options = new {Ui}ListboxOption[] {{ {string.Join(", ", options.Select(o => $"new({Literal(o.Value)}, {Literal(o.Label)})"))} }}");
        if (inits.Count > 0) info.Append(" { ").Append(string.Join(", ", inits)).Append(" }");

        var conditions = ConditionsOf(owner, self, formField, location, diagnostics);
        var tail = conditions is null ? "" : $", {conditions}";
        return kind switch
        {
            "Object" => $"{Ui}SchemaField<{self}>.Object<{type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(typeFormat)}>({info}, static m => m.{name}{tail})",
            "List" => $"{Ui}SchemaField<{self}>.List<{itemType}>({info}, static m => m.{name}{tail})",
            _ => $"{Ui}SchemaField<{self}>.Value<{type.ToDisplayString(typeFormat)}>({info}, static m => m.{name}, static (m, v) => m.{name} = v, static m => () => m.{name}, {renderer}{tail})",
        };
    }

    /// <summary>与 Rune.UI.SchemaControl 的成员一一对应。</summary>
    enum Control { Auto, Text, Textarea, Number, Switch, Checkbox, Select, Radio, MultiSelect, Checkboxes, Date, DateTime, Object, List, Table, People, File }

    /// <summary>值字段的控件与渲染函数：按 [FormField(Control)]，没写时按类型选。</summary>
    static (string? Control, string? Renderer, string? Error) ControlOf(IPropertySymbol property, ITypeSymbol type, int asked, bool hasDates,
        out IReadOnlyList<(string Value, string Label)> options)
    {
        options = [];
        var nullable = type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } wrapper ? wrapper.TypeArguments[0] : null;
        var core = nullable ?? type;
        var full = type.ToDisplayString(typeFormat);
        var requested = (Control)asked;
        string? Choose(Control fallback, params Control[] allowed) => requested == Control.Auto ? fallback.ToString() : allowed.Contains(requested) ? requested.ToString() : null;
        (string?, string?, string?) Wrong() => (null, null, $"类型 {type.ToDisplayString()} 不能用 {requested} 控件");

        if (core.SpecialType == SpecialType.System_String)
        {
            var source = Named(Attribute(property, "Rune.UI.FormFieldAttribute"), "Source") is string;
            var max = MaxLengthOf(property);
            var multiline = Named(Attribute(property, "System.ComponentModel.DataAnnotations.DataTypeAttribute"), null) is 9 /* DataType.MultilineText */;
            var fallback = source ? Control.Select : multiline || max > 100 ? Control.Textarea : Control.Text;
            var control = Choose(fallback, Control.Text, Control.Textarea, Control.Select, Control.Radio);
            return control is null ? Wrong() : (control, $"{Ui}SchemaControls.{control}", null);
        }
        if (core.SpecialType == SpecialType.System_Boolean && nullable is null)
        {
            var control = Choose(Control.Switch, Control.Switch, Control.Checkbox);
            return control is null ? Wrong() : (control, $"{Ui}SchemaControls.{control}", null);
        }
        if (IsNumeric(core))
        {
            var control = Choose(Control.Number, Control.Number);
            return control is null ? Wrong() : (control, $"{Ui}SchemaControls.Number<{full}>", null);
        }
        if (core.TypeKind == TypeKind.Enum)
        {
            options = EnumOptions(core);
            var control = Choose(Control.Select, Control.Select, Control.Radio);
            if (control is null) return Wrong();
            var prefix = nullable is null ? "Enum" : "NullableEnum";
            return (control, $"{Ui}SchemaControls.{prefix}{control}<{core.ToDisplayString(typeFormat)}>", null);
        }
        var coreName = core.ToDisplayString();
        if (coreName is "System.DateOnly" or "System.DateTime" or "System.DateTimeOffset")
        {
            if (!hasDates) return (null, null, "日期字段要引用 Rune.UI.Dates（DatePicker）");
            var control = Choose(coreName == "System.DateOnly" ? Control.Date : Control.DateTime, Control.Date, Control.DateTime);
            return control is null ? Wrong() : (control, $"{Ui}SchemaDateControls.{control}<{full}>", null);
        }
        if (ReadOnlyListItemOf(type) is { } item)
        {
            var itemName = item.ToDisplayString();
            if (item.SpecialType == SpecialType.System_String)
            {
                var control = Choose(Control.MultiSelect, Control.MultiSelect, Control.Checkboxes);
                return control is null ? Wrong() : (control, $"{Ui}SchemaControls.{control}", null);
            }
            if (item.TypeKind == TypeKind.Enum)
            {
                options = EnumOptions(item);
                var control = Choose(Control.MultiSelect, Control.MultiSelect, Control.Checkboxes);
                return control is null ? Wrong() : (control, $"{Ui}SchemaControls.Enum{control}<{item.ToDisplayString(typeFormat)}>", null);
            }
            if (itemName == "Rune.UI.PeopleEntry") return Choose(Control.People, Control.People) is { } c ? (c, $"{Ui}SchemaControls.People", null) : Wrong();
            if (itemName == "Rune.UI.UploadFile") return Choose(Control.File, Control.File) is { } f ? (f, $"{Ui}SchemaControls.File", null) : Wrong();
        }
        return (null, null, $"类型 {type.ToDisplayString()} 生成不了控件（文字、数字、布尔、枚举、日期、IReadOnlyList<string / 枚举 / PeopleEntry / UploadFile>、[FormSchema] 的对象与列表）；用 [ScaffoldColumn(false)] 跳过，或在 SchemaForm 的 Fields 里自己渲染");
    }

    /// <summary>条件：模型上 bool 属性或无参方法的名字 → <c>static m =&gt; m.X</c>。</summary>
    static string? ConditionsOf(INamedTypeSymbol owner, string self, AttributeData? formField, Location location, List<DiagnosticInfo> diagnostics)
    {
        var parts = new List<string>();
        foreach (var name in new[] { "VisibleWhen", "RequiredWhen", "ReadOnlyWhen" })
        {
            if (Named(formField, name) is not string member) continue;
            var symbol = MembersOf(owner, member).FirstOrDefault(m =>
                m is IPropertySymbol { Type.SpecialType: SpecialType.System_Boolean, IsStatic: false }
                || m is IMethodSymbol { ReturnType.SpecialType: SpecialType.System_Boolean, Parameters.Length: 0, IsStatic: false });
            if (symbol is null)
            {
                diagnostics.Add(DiagnosticInfo.Create(Generators.Diagnostics.FormSchemaCondition, location, member, owner.Name));
                continue;
            }
            parts.Add($"{name}: static m => m.{member}{(symbol is IMethodSymbol ? "()" : "")}");
        }
        return parts.Count == 0 ? null : $"new {Ui}SchemaConditions<{self}>({string.Join(", ", parts)})";
    }

    static IEnumerable<ISymbol> MembersOf(INamedTypeSymbol type, string name)
    {
        for (var current = type; current is not null; current = current.BaseType)
            foreach (var member in current.GetMembers(name)) yield return member;
    }

    static List<(string Value, string Label)> EnumOptions(ITypeSymbol type) =>
        [.. type.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue)
            .Select(f => (f.Name, Named(Attribute(f, "System.ComponentModel.DataAnnotations.DisplayAttribute"), "Name") as string ?? f.Name))];

    static bool HasFormSchema(ITypeSymbol type) =>
        type is INamedTypeSymbol { TypeKind: TypeKind.Class } && type.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "Rune.UI.FormSchemaAttribute");

    /// <summary>List&lt;T&gt;、IList&lt;T&gt; 的元素（可增删的列表）。</summary>
    static ITypeSymbol? ListItemOf(ITypeSymbol type) =>
        type is INamedTypeSymbol { IsGenericType: true } named
        && named.OriginalDefinition.ToDisplayString() is "System.Collections.Generic.List<T>" or "System.Collections.Generic.IList<T>"
            ? named.TypeArguments[0] : null;

    /// <summary>IReadOnlyList&lt;T&gt; 的元素（多选的值）。</summary>
    static ITypeSymbol? ReadOnlyListItemOf(ITypeSymbol type) =>
        type is INamedTypeSymbol { IsGenericType: true } named && named.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IReadOnlyList<T>"
            ? named.TypeArguments[0] : null;

    static bool IsNumeric(ITypeSymbol type) => type.SpecialType is SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Int16
        or SpecialType.System_UInt16 or SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64
        or SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_Decimal;

    static int MaxLengthOf(IPropertySymbol property)
    {
        foreach (var name in new[] { "System.ComponentModel.DataAnnotations.StringLengthAttribute", "System.ComponentModel.DataAnnotations.MaxLengthAttribute" })
            if (Attribute(property, name)?.ConstructorArguments.FirstOrDefault().Value is int max) return max;
        return 0;
    }

    static AttributeData? Attribute(ISymbol symbol, string name) =>
        symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == name);

    /// <summary>特性的命名参数；name 为 null 时取第一个构造参数（[DataType(DataType.MultilineText)]）。</summary>
    static object? Named(AttributeData? attribute, string? name)
    {
        if (attribute is null) return null;
        if (name is null) return attribute.ConstructorArguments.FirstOrDefault().Value;
        foreach (var argument in attribute.NamedArguments)
            if (argument.Key == name) return argument.Value.Value;
        return null;
    }

    /// <summary>类型与包含它的类型都要是 partial 才能补上实现。</summary>
    static bool IsPartialChain(INamedTypeSymbol type, CancellationToken cancellation)
    {
        for (var current = type; current is not null; current = current.ContainingType)
        {
            var partial = current.DeclaringSyntaxReferences.Any(reference =>
                reference.GetSyntax(cancellation) is TypeDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
            if (!partial) return false;
        }
        return true;
    }

    static string DeclarationOf(INamedTypeSymbol type)
    {
        var kind = type switch
        {
            { IsRecord: true, IsValueType: true } => "record struct",
            { IsRecord: true } => "record",
            { IsValueType: true } => "struct",
            _ => "class",
        };
        return $"partial {kind} {type.Name}";
    }

    static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

    static string Indent(string text) =>
        string.Join("\n", text.TrimEnd().Split('\n').Select(line => line.TrimEnd('\r')).Select(line => line.Length == 0 ? line : "    " + line));
}
