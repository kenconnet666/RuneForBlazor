#!/usr/bin/env node
// 从 Radix Colors（npm 包 @radix-ui/colors）生成主题编辑器用的色阶（RadixColors.g.cs）：品牌色、中性色各一组，亮色与暗色各 12 级。
// 同 vue-tsx-pro 的 theme-customize/palette.ts：内置主题的配色就是按这些色阶取的（indigo 品牌色、slate 中性色），
// 主题编辑器换品牌色、中性色时整组替换。哪个 token 取第几级写在 C# 的 ThemePalette 里。
//
// 用法：node tools/palette-gen/generate.mjs [--source <@radix-ui/colors 的 package 目录>] [--check]
//   --source  已解压的包目录；不写时用 npm pack 下载 RADIX_VERSION 到临时目录
//   --check   只比较不写入；生成文件与现有内容不一致时以非零状态退出（CI 用）
//
// 输出：
//   src/Rune.UI/Config/Theme/Customize/RadixColors.g.cs   色阶（AccentScale、NeutralScale 与各级的颜色）
//   src/Rune.UI/LICENSE-radix-colors.txt                  Radix Colors 的许可（随 Rune.UI 包分发）
//
// 依赖：node 内置模块；下载时用 npm 与 tar。数据来源与许可见 NOTICE.md。

import { execFileSync, execSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

/** 使用的 Radix Colors 版本（同 vue-tsx-pro 的依赖）；升级时改这里并重新生成 */
const RADIX_VERSION = '3.0.0';

/** 品牌色：Radix 的彩色色阶，按色相排列（同 vue-tsx-pro 的 ACCENT_TABLE） */
const ACCENTS = ['tomato', 'red', 'ruby', 'crimson', 'pink', 'plum', 'purple', 'violet', 'iris', 'indigo', 'blue', 'sky', 'cyan', 'teal',
  'jade', 'mint', 'green', 'grass', 'lime', 'yellow', 'amber', 'orange', 'brown', 'bronze', 'gold'];

/** 中性色：Radix 的灰色色阶（同 vue-tsx-pro 的 NEUTRAL_TABLE） */
const NEUTRALS = ['slate', 'gray', 'mauve', 'sage', 'olive', 'sand'];

const repoRoot = resolve(import.meta.dirname, '../..');
const outputPath = resolve(repoRoot, 'src/Rune.UI/Config/Theme/Customize/RadixColors.g.cs');
const licensePath = resolve(repoRoot, 'src/Rune.UI/LICENSE-radix-colors.txt');

const { values } = parseArgs({
  options: {
    source: { type: 'string' },
    check: { type: 'boolean', default: false },
  },
});

/** 取得包目录：指定的目录，或下载到临时目录（返回清理函数） */
function obtainPackage() {
  if (values.source) return { dir: resolve(values.source), cleanup: () => {} };
  const temp = mkdtempSync(join(tmpdir(), 'rune-radix-'));
  // Windows 上 npm 是 npm.cmd，要经 shell 执行；命令里只有固定的版本号
  execSync(`npm pack @radix-ui/colors@${RADIX_VERSION} --silent`, { cwd: temp, stdio: ['ignore', 'ignore', 'inherit'] });
  execFileSync('tar', ['-xzf', `radix-ui-colors-${RADIX_VERSION}.tgz`], { cwd: temp, stdio: 'inherit' });
  return { dir: join(temp, 'package'), cleanup: () => rmSync(temp, { recursive: true, force: true }) };
}

const pascal = (name) => name.charAt(0).toUpperCase() + name.slice(1);

const { dir, cleanup } = obtainPackage();
let colors;
let license;
try {
  colors = createRequire(join(dir, 'package.json'))(join(dir, 'index.js'));
  license = readFileSync(join(dir, 'LICENSE'), 'utf8').replaceAll('\r\n', '\n');
} finally {
  cleanup();
}

/** 一个色阶的 12 级：亮色或暗色 */
function steps(name, dark) {
  const scale = colors[dark ? `${name}Dark` : name];
  if (!scale) throw new Error(`@radix-ui/colors 里没有 ${name}${dark ? 'Dark' : ''}`);
  return Array.from({ length: 12 }, (_, index) => {
    const value = scale[`${name}${index + 1}`];
    if (!/^#[0-9a-f]{6}$/i.test(value ?? '')) throw new Error(`${name}${dark ? 'Dark' : ''} 第 ${index + 1} 级不是 #rrggbb：${value}`);
    return value.toLowerCase();
  });
}

const array = (name, dark) => `    static readonly string[] ${pascal(name)}${dark ? 'Dark' : ''} = [${steps(name, dark).map((v) => `"${v}"`).join(', ')}];`;
const enumMembers = (names) => names.map((name) => `    /// <summary>${name}</summary>\n    ${pascal(name)},`).join('\n\n');
const cases = (type, names) => names.map((name) => `        ${type}.${pascal(name)} => dark ? ${pascal(name)}Dark : ${pascal(name)},`).join('\n');

const output = [
  '// <auto-generated>',
  `// 由 tools/palette-gen/generate.mjs 从 @radix-ui/colors ${RADIX_VERSION} 生成，请勿手改。许可见 LICENSE-radix-colors.txt。`,
  '// </auto-generated>',
  '#nullable enable',
  '',
  'namespace Rune.UI;',
  '',
  '/// <summary>主题编辑器可选的品牌色（Radix 的彩色色阶），按色相排列。</summary>',
  'public enum AccentScale',
  '{',
  enumMembers(ACCENTS),
  '}',
  '',
  '/// <summary>主题编辑器可选的中性色（Radix 的灰色色阶，各带一点色相：indigo 配 slate、crimson 配 mauve……）。</summary>',
  'public enum NeutralScale',
  '{',
  enumMembers(NEUTRALS),
  '}',
  '',
  '/// <summary>Radix Colors 的色阶：每个 12 级（下标 0 是第 1 级），亮色与暗色各一组。</summary>',
  'internal static class RadixColors',
  '{',
  '    /// <summary>品牌色色阶的 12 级。</summary>',
  '    internal static IReadOnlyList<string> Of(AccentScale scale, bool dark) => scale switch',
  '    {',
  cases('AccentScale', ACCENTS),
  '        _ => throw new ArgumentOutOfRangeException(nameof(scale)),',
  '    };',
  '',
  '    /// <summary>中性色色阶的 12 级。</summary>',
  '    internal static IReadOnlyList<string> Of(NeutralScale scale, bool dark) => scale switch',
  '    {',
  cases('NeutralScale', NEUTRALS),
  '        _ => throw new ArgumentOutOfRangeException(nameof(scale)),',
  '    };',
  '',
  ...[...ACCENTS, ...NEUTRALS].flatMap((name) => [array(name, false), array(name, true)]),
  '}',
  '',
].join('\n');

if (values.check) {
  const stale = [[outputPath, output], [licensePath, license]].filter(([path, content]) =>
    !existsSync(path) || readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== content);
  if (stale.length) {
    console.error(`已过期：${stale.map(([path]) => path).join('、')}`);
    process.exit(1);
  }
  console.log('生成文件与数据源一致');
} else {
  writeFileSync(outputPath, output);
  writeFileSync(licensePath, license);
  console.log(`已写入 ${outputPath}：${ACCENTS.length} 个品牌色、${NEUTRALS.length} 个中性色`);
}
