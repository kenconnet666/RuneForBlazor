#!/usr/bin/env node
// 从 vue-tsx-pro 已生成的 CSS 属性说明（documented.ts）生成 C# 的强类型样式属性表与 CSS 关键字常量。
//
// 用法：node tools/css-gen/generate.mjs [--source <vue-tsx-pro 根目录>] [--check]
//   --source  vue-tsx-pro 仓库根目录，默认 ../../IdeaProjects/vue-tsx-pro（相对本仓库根）
//   --check   只比较不写入；任一生成文件与现有内容不一致时以非零状态退出
//
// 输出：Style.Properties.g.cs（属性表）、CssKeywords.g.cs（每个有专属关键字的属性一个静态类，如 Display.Flex）。
//
// 零依赖：只用 node: 内置模块，按固定的行格式解析 .ts 文件，不引 TypeScript 编译器。
// 数据来源与许可见 NOTICE.md。

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, extname, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const repoRoot = resolve(import.meta.dirname, '../..');
const stylesOutDir = resolve(repoRoot, 'src/Rune/Styles');
const propertiesPath = resolve(stylesOutDir, 'Style.Properties.g.cs');
const keywordsPath = resolve(stylesOutDir, 'CssKeywords.g.cs');

const GENERATED_HEADER = [
  '// <auto-generated>',
  '// 由 tools/css-gen/generate.mjs 生成，请勿手改；数据来源见 tools/css-gen/NOTICE.md。',
  '// </auto-generated>',
  '#nullable enable',
  '',
];

/** 关键字类与 Rune.Styles 已有类型（或 Rune.UI 的组件）重名时加的后缀 */
const KEYWORD_CLASS_SUFFIX = 'Keywords';

/**
 * Rune.UI 里与关键字类同名的组件：页面通常同时 using Rune.Styles 与 Rune.UI，C# 代码里同名会有歧义，关键字类加后缀让路。
 * 组件库新增与 CSS 属性同名的组件时加在这里
 */
const COMPONENT_NAMES = ['Flex', 'Grid'];

/** 不生成常量的关键字接口：颜色名、系统色等量大且直接写字符串更合适；CSS 全局关键字单独放 CssWide */
const SKIPPED_KEYWORD_GROUPS = new Set(['CssWideKeywords', 'CssColor', 'CssColorBase', 'CssNamedColor', 'CssSystemColor']);

/** 属性至少有这么多专属关键字才生成类：只有一个 `auto` 之类的属性，常量不比字符串更好写 */
const MIN_KEYWORDS = 2;

/** Style 里已有的成员名，生成的属性不能与之重名 */
const RESERVED_MEMBERS = new Set(['Set', 'Declarations', 'Conditions', 'Compiled', 'Item']);

/** 带这些措辞的条目在数据里被标为“不是真实 CSS 属性”，不生成 */
const NOT_A_PROPERTY = /非标准键|不是元素样式属性|无前缀.*尚未支持/;

/** 值类型里出现这些 token 组时视为长度（数字补 px，也可以是间距、尺寸类 token） */
const LENGTH_TOKEN_GROUPS = new Set([
  'Space',
  'Sizes',
  'Radii',
  'BorderWidths',
  'FontSizes',
  'LetterSpacings',
  'StrokeWidths',
]);

const VENDOR_PREFIXES = { Webkit: '-webkit-', Moz: '-moz-', Ms: '-ms-' };

/**
 * Rune.Styles 目录里手写的类型名（含嵌套类型与 .razor 组件），关键字类不能同名。
 * 每次从源码扫描，新增类型后重新生成即可发现冲突。
 */
function existingTypeNames() {
  const names = new Set(['CssWide', ...COMPONENT_NAMES]);
  const declaration =
    /^\s*(?:(?:public|internal|private|protected|sealed|static|readonly|abstract|partial|file)\s+)*(?:class|struct|enum|interface|record(?:\s+(?:struct|class))?)\s+(\w+)/;
  for (const file of readdirSync(stylesOutDir)) {
    if (file.endsWith('.g.cs')) continue;
    if (extname(file) === '.razor') names.add(basename(file, '.razor'));
    if (extname(file) !== '.cs') continue;
    for (const line of readFileSync(resolve(stylesOutDir, file), 'utf8').split(/\r?\n/)) {
      const name = line.match(declaration)?.[1];
      if (name) names.add(name);
    }
  }
  return names;
}

const { values } = parseArgs({
  options: {
    source: { type: 'string', default: resolve(repoRoot, '../../IdeaProjects/vue-tsx-pro') },
    check: { type: 'boolean', default: false },
  },
});
const sourceRoot = resolve(values.source);
const stylesDir = resolve(sourceRoot, 'packages/tsx/src/styles');

/** 读文件并统一成 LF，缺文件时给出明确的报错 */
function readSource(name) {
  const path = resolve(stylesDir, name);
  if (!existsSync(path)) {
    console.error(`找不到 ${path}；用 --source 指定 vue-tsx-pro 根目录`);
    process.exit(2);
  }
  return readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
}

// ---------- units.ts：数字值的单位规则 ----------

function parseUnits(text) {
  const unitless = text.match(/UNITLESS = new Set\(\s*'([^']+)'/);
  const milliseconds = text.match(/MILLISECONDS = new Set\(\[([^\]]+)\]/);
  if (!unitless || !milliseconds) throw new Error('units.ts 的格式变了：找不到 UNITLESS / MILLISECONDS');
  return {
    unitless: new Set(unitless[1].split(' ')),
    milliseconds: new Set([...milliseconds[1].matchAll(/'(\w+)'/g)].map((m) => m[1])),
  };
}

// ---------- documented.ts：属性与 JSDoc ----------

/**
 * 解析 `interface DocumentedStyles` 里的属性。
 * 每项是一段 2 空格缩进的 JSDoc，后面跟一条以 `;` 结束的声明（可跨多行）。
 * 伪元素（`'::after'?: …`）不是属性，直接忽略。
 */
function parseDocumented(text) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.startsWith('export interface DocumentedStyles'));
  if (start < 0) throw new Error('documented.ts 的格式变了：找不到 DocumentedStyles');
  const entries = [];
  for (let i = start + 1; lines[i] !== '}'; i++) {
    if (lines[i] !== '  /**') continue;
    const doc = [];
    for (i++; lines[i] !== '   */'; i++) doc.push(lines[i].replace(/^ {3}\* ?/, ''));
    let declaration = '';
    for (i++; ; i++) {
      declaration += lines[i].trim() + ' ';
      if (lines[i].trimEnd().endsWith(';')) break;
    }
    const head = declaration.match(/^(\w+)\?: StyleValue</);
    if (head) entries.push({ name: head[1], doc, declaration });
  }
  return entries;
}

/**
 * 解析所有 `interface Xxx { 键: unknown }`：每个键是一个 CSS 关键字，键上的 JSDoc 是 “`关键字`：说明”。
 * 返回 接口名 → [{ keyword, doc }]（保持文件里的顺序）。
 */
function parseKeywordInterfaces(text) {
  const lines = text.split('\n');
  const interfaces = new Map();
  for (let i = 0; i < lines.length; i++) {
    const head = lines[i].match(/^interface (\w+) \{$/);
    if (!head) continue;
    const keywords = [];
    let doc = [];
    for (i++; lines[i] !== '}'; i++) {
      if (lines[i] === '  /**') {
        doc = [];
        for (i++; lines[i] !== '   */'; i++) doc.push(lines[i].replace(/^ {3}\* ?/, '').trim());
        continue;
      }
      const key = lines[i].match(/^ {2}(?:'([^']+)'|([\w-]+)): unknown;$/);
      if (key) keywords.push({ keyword: key[1] ?? key[2], doc: doc.join(' ').replace(/^`[^`]+`[：:]\s*/, '') });
      doc = [];
    }
    interfaces.set(head[1], keywords);
  }
  return interfaces;
}

/** 值类型引用的关键字接口，如 `keyof AlignItemsKeywords`、`KeywordValue<DisplayValues, …>`；token 组（…Tokens）不是关键字 */
function keywordGroups(declaration) {
  const names = [...declaration.matchAll(/keyof (\w+)|KeywordValue<(\w+),/g)].map((m) => m[1] ?? m[2]);
  return [...new Set(names)].filter((n) => !n.endsWith('Tokens'));
}

/** 值类型里引用的主题 token 组，如 `keyof QualifiedColorsTokens` → Colors */
function tokenGroups(declaration) {
  const groups = [...declaration.matchAll(/keyof (?:Qualified)?(\w+)Tokens/g)].map((m) => m[1]);
  return new Set(groups);
}

// ---------- 命名 ----------

const csharpName = (name) => name[0].toUpperCase() + name.slice(1);

const compareOrdinal = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** CSS 关键字 → C# 成员名：按连字符、空格切词转 PascalCase（`first baseline` → FirstBaseline，`-webkit-box` → WebkitBox）；数字开头加下划线 */
function keywordMemberName(keyword) {
  const name = keyword
    .split(/[-\s]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
  return /^\d/.test(name) ? '_' + name : name;
}

function cssName(name) {
  const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
  const vendor = Object.keys(VENDOR_PREFIXES).find((p) => name.startsWith(p) && /^[A-Z]/.test(name.slice(p.length)));
  if (vendor) return VENDOR_PREFIXES[vendor] + kebab(name.slice(vendor.length)).replace(/^-/, '');
  return kebab(name);
}

// ---------- 文档注释 ----------

const escapeXml = (s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

/** 行内文本：转义 XML，反引号包起来的部分变成 <c> */
function inline(text) {
  return text
    .split('`')
    .map((part, i) => (i % 2 === 1 ? `<c>${escapeXml(part)}</c>` : escapeXml(part)))
    .join('');
}

/**
 * JSDoc 行 → 段落、列表、@see 链接。
 * 空行分段；`- ` 开头的连续行是列表（缩进的后续行并入上一项）；`@see` 之外的 `@` 开头行当普通文字
 * （如 “@font-face 中字体…”）。
 */
function parseDoc(lines) {
  const blocks = [];
  const links = [];
  let paragraph = null;
  let list = null;
  const flush = () => {
    paragraph = null;
    list = null;
  };
  for (const line of lines) {
    const see = line.match(/^@see (\S+)\s*$/);
    if (see) {
      links.push(see[1]);
      flush();
    } else if (line.trim() === '') {
      flush();
    } else if (line.startsWith('- ')) {
      paragraph = null;
      if (!list) blocks.push((list = { list: [] }));
      list.list.push(line.slice(2));
    } else if (list && line.startsWith(' ')) {
      list.list[list.list.length - 1] += ' ' + line.trim();
    } else {
      list = null;
      if (paragraph) paragraph.text += ' ' + line.trim();
      else blocks.push((paragraph = { text: line.trim() }));
    }
  }
  return { blocks, links };
}

/** 生成属性前的 /// 注释行（含 summary、remarks、seealso） */
function docComment(lines, indent) {
  const { blocks, links } = parseDoc(lines);
  const [first, ...rest] = blocks;
  if (!first?.text) throw new Error('JSDoc 第一段不是文字，无法作为 summary');
  const out = [`<summary>${inline(first.text)}</summary>`];
  if (rest.length > 0) {
    out.push('<remarks>');
    for (const block of rest) {
      if (block.list) {
        out.push('<list type="bullet">');
        for (const item of block.list) out.push(`<item><description>${inline(item)}</description></item>`);
        out.push('</list>');
      } else {
        out.push(`<para>${inline(block.text)}</para>`);
      }
    }
    out.push('</remarks>');
  }
  for (const href of links) out.push(`<seealso href="${escapeXml(href).replaceAll('"', '&quot;')}"/>`);
  return out.map((l) => `${indent}/// ${l}`);
}

// ---------- 分类与生成 ----------

/**
 * 决定 C# 类型与调用。
 * 颜色 token → CssColor；长度 token → CssLength；其余 → CssValue 并带单位规则。
 * 长度属性若按单位规则数字不补 px（如 strokeWidth），改用 CssValue，否则数字会被错补 px。
 */
function classify(name, groups, units) {
  const unit = units.unitless.has(name) ? 'None' : units.milliseconds.has(name) ? 'Milliseconds' : 'Pixels';
  const hasColor = groups.has('Colors');
  const hasLength = [...groups].some((g) => LENGTH_TOKEN_GROUPS.has(g));
  if (hasColor && hasLength) return { kind: 'value', unit, note: '同时接受颜色与长度 token' };
  if (hasColor) return { kind: 'color' };
  if (hasLength && unit !== 'Pixels') return { kind: 'value', unit, note: `长度 token 但数字不补 px（${unit}）` };
  if (hasLength) return { kind: 'length' };
  return { kind: 'value', unit };
}

/** 属性表（Style.Properties.g.cs） */
function generateProperties(properties) {
  const members = [...properties].sort((a, b) => compareOrdinal(a.csName, b.csName));
  return [
    ...GENERATED_HEADER,
    'namespace Rune.Styles;',
    '',
    'public sealed partial class Style',
    '{',
    members.map((m) => m.text).join('\n\n'),
    '}',
    '',
  ].join('\n');
}

/** 一个关键字的 <summary>：`<c>关键字</c>：说明`，没有说明时只写关键字 */
function keywordSummary({ keyword, doc }) {
  return `<summary><c>${escapeXml(keyword)}</c>${doc ? '：' + inline(doc) : ''}</summary>`;
}

/**
 * 关键字常量（CssKeywords.g.cs）。
 * 专属关键字数 ≥ MIN_KEYWORDS 的属性各一个静态类，成员类型与属性在 Style 里的类型一致，可直接赋值；
 * 另有 CssWide 放 CSS 全局关键字（字符串常量，对 CssValue / CssLength / CssColor 都能隐式转换）。
 */
function generateKeywords(properties, interfaces, warnings) {
  const reserved = existingTypeNames();
  const wide = interfaces.get('CssWideKeywords') ?? [];
  const wideKeywords = new Set(wide.map((k) => k.keyword));
  const classes = [];
  const fewKeywords = [];

  for (const property of properties) {
    const seen = new Set();
    const keywords = [];
    for (const group of property.keywordGroups) {
      if (SKIPPED_KEYWORD_GROUPS.has(group)) continue;
      const list = interfaces.get(group);
      if (!list) {
        warnings.push(`${property.name}：找不到关键字接口 ${group}`);
        continue;
      }
      for (const entry of list) {
        if (wideKeywords.has(entry.keyword) || seen.has(entry.keyword)) continue;
        seen.add(entry.keyword);
        keywords.push({ ...entry });
      }
    }
    if (keywords.length < MIN_KEYWORDS) {
      if (keywords.length > 0) fewKeywords.push(property.name);
      continue;
    }

    let className = property.csName;
    if (reserved.has(className)) {
      className += KEYWORD_CLASS_SUFFIX;
      warnings.push(`${property.csName} 与 Rune.Styles 已有类型重名，关键字类改名为 ${className}`);
    }
    const members = new Map();
    for (const entry of keywords) {
      entry.name = keywordMemberName(entry.keyword);
      if (entry.name === className) {
        // C# 不允许成员与所在类型同名
        entry.name += 'Value';
        warnings.push(`${className}：关键字 ${entry.keyword} 与类同名，成员改名为 ${entry.name}`);
      }
      if (members.has(entry.name)) {
        warnings.push(`${className}：关键字 ${entry.keyword} 与 ${members.get(entry.name).keyword} 生成了相同的成员名 ${entry.name}，已丢弃`);
        continue;
      }
      members.set(entry.name, entry);
    }
    classes.push({ className, members: [...members.values()].sort((a, b) => compareOrdinal(a.name, b.name)), property });
  }
  classes.sort((a, b) => compareOrdinal(a.className, b.className));

  const wideClass = [
    '/// <summary>CSS 全局关键字，任何属性都接受；是字符串常量，可直接赋给 <see cref="CssValue"/>、<see cref="CssLength"/>、<see cref="CssColor"/>。</summary>',
    'public static class CssWide',
    '{',
    wide
      .map((k) => ({ ...k, name: keywordMemberName(k.keyword) }))
      .sort((a, b) => compareOrdinal(a.name, b.name))
      .map((m) => `    /// ${keywordSummary(m)}\n    public const string ${m.name} = "${m.keyword}";`)
      .join('\n\n'),
    '}',
  ].join('\n');

  const classTexts = classes.map(({ className, members, property }) =>
    [
      `/// <summary><c>${escapeXml(property.css)}</c> 的关键字取值；类型与 <see cref="Style.${property.csName}"/> 一致，可直接赋值。</summary>`,
      `public static class ${className}`,
      '{',
      members
        .map((m) => `    /// ${keywordSummary(m)}\n    public static readonly ${property.type} ${m.name} = "${m.keyword}";`)
        .join('\n\n'),
      '}',
    ].join('\n'),
  );
  const content = [...GENERATED_HEADER, 'namespace Rune.Styles;', '', [wideClass, ...classTexts].join('\n\n'), ''].join('\n');
  return {
    content,
    classCount: classes.length,
    memberCount: classes.reduce((n, c) => n + c.members.length, 0),
    fewKeywords,
  };
}

function generate() {
  const units = parseUnits(readSource('units.ts'));
  const documentedText = readSource('documented.ts');
  const entries = parseDocumented(documentedText);
  const interfaces = parseKeywordInterfaces(documentedText);
  const warnings = [];
  const skipped = [];
  const notes = [];
  const counts = { color: 0, length: 0, value: 0 };
  const seen = new Map();
  const properties = [];

  for (const entry of entries) {
    if (NOT_A_PROPERTY.test(entry.doc[0])) {
      skipped.push(`${entry.name}（${entry.doc[0]}）`);
      continue;
    }
    const csName = csharpName(entry.name);
    const css = cssName(entry.name);
    if (RESERVED_MEMBERS.has(csName)) warnings.push(`${entry.name} 与 Style 已有成员 ${csName} 重名`);
    if (seen.has(csName)) warnings.push(`${entry.name} 与 ${seen.get(csName)} 生成了相同的 C# 名 ${csName}`);
    seen.set(csName, entry.name);

    // 说明里写的 CSS 名与按命名规则推出的不一致时提示（说明里第一处括号里的连字符名）
    const documented = entry.doc[0].match(/[（(](-?[a-z][a-z-]*)[）)]/)?.[1];
    if (documented && documented !== css) warnings.push(`${entry.name}：说明里写 ${documented}，推出 ${css}`);

    const cls = classify(entry.name, tokenGroups(entry.declaration), units);
    if (cls.note) notes.push(`${entry.name}：${cls.note}`);
    counts[cls.kind]++;
    const [type, call] = {
      color: ['CssColor', `Set("${css}", value)`],
      length: ['CssLength', `Set("${css}", value)`],
      value: ['CssValue', `Set("${css}", value, NumberUnit.${cls.unit})`],
    }[cls.kind];
    properties.push({
      name: entry.name,
      csName,
      css,
      type,
      keywordGroups: keywordGroups(entry.declaration),
      text: [...docComment(entry.doc, '    '), `    public ${type}? ${csName} { init => ${call}; }`].join('\n'),
    });
  }

  const keywords = generateKeywords(properties, interfaces, warnings);
  const files = [
    { path: propertiesPath, content: generateProperties(properties) },
    { path: keywordsPath, content: keywords.content },
  ];
  return { files, total: properties.length, keywords, counts, skipped, warnings, notes };
}

// ---------- 入口 ----------

const result = generate();
for (const w of result.warnings) console.warn(`警告：${w}`);

if (values.check) {
  // 按 LF 比较：Windows 上 git 可能把工作区文件换成 CRLF
  let stale = false;
  for (const { path, content } of result.files) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replaceAll('\r\n', '\n') : null;
    if (current !== content) {
      console.error(`${basename(path)} 与数据源不一致，请运行 node tools/css-gen/generate.mjs`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('生成文件与数据源一致');
} else {
  for (const { path, content } of result.files) writeFileSync(path, content);
  const { total, counts, skipped, notes, keywords } = result;
  console.log(`已生成 ${total} 个属性：CssColor ${counts.color}、CssLength ${counts.length}、CssValue ${counts.value}`);
  console.log(`已生成 ${keywords.classCount} 个关键字类、${keywords.memberCount} 个关键字常量`);
  console.log(`专属关键字不足 ${MIN_KEYWORDS} 个而跳过的属性 ${keywords.fewKeywords.length} 个：${keywords.fewKeywords.join('、')}`);
  console.log(`跳过 ${skipped.length} 个非 CSS 属性：\n  ${skipped.join('\n  ')}`);
  if (notes.length > 0) console.log(`分类说明：\n  ${notes.join('\n  ')}`);
}
