#!/usr/bin/env node
// 从 @lucide/icons 生成 C# 的图标数据：全集（Rune.Icons 包）与组件库内置的小集合（Rune.UI）。
//
// 用法：node tools/icon-gen/generate.mjs [--source <@lucide/icons 目录>] [--check]
//   --source  @lucide/icons 包目录，默认 vue-tsx-pro 依赖里的 1.59.0
//   --check   只比较不写入；任一生成文件与现有内容不一致时以非零状态退出
//
// 输出：
//   src/Rune.Icons/Lucide.g.cs           全集，Rune.Icons.Lucide.Plus
//   src/Rune.UI/Icons/BuiltInIcons.g.cs  组件库自己要用的图标（见 BUILT_IN），Rune.UI.BuiltInIcons.Plus
//
// 数据格式：dist/esm/icons/<name>.mjs 默认导出 { name, size, node: [[标签, 属性]...] }，
// 属性里的 key 是框架用的无关字段，生成时丢弃。数据里没有分类与标签，文档注释只写图标名。
// 每个图标一个“按需创建”的静态属性（field ??=），避免类型初始化时一次建出全部对象，也便于 WebAssembly 发布时裁剪未用到的成员。
//
// 零依赖：只用 node: 内置模块。数据来源与许可见 NOTICE.md。

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const repoRoot = resolve(import.meta.dirname, '../..');
const lucidePath = resolve(repoRoot, 'src/Rune.Icons/Lucide.g.cs');
const builtInPath = resolve(repoRoot, 'src/Rune.UI/Icons/BuiltInIcons.g.cs');

/** 组件库内置的图标：组件自己要用的，新增组件需要图标时往这里加一项再重新生成 */
const BUILT_IN = [
  'x',
  'check',
  'chevron-down',
  'chevron-up',
  'chevron-left',
  'chevron-right',
  'info',
  'circle-check',
  'triangle-alert',
  'circle-alert',
  'minus',
  'plus',
  'search',
  'loader-circle',
  'external-link',
  'copy',
];

/** 属性名不能取的名字：object 的成员与所在类自身（C# 关键字都是小写，PascalCase 后不会冲突） */
const RESERVED_MEMBERS = new Set(['Equals', 'GetHashCode', 'GetType', 'ToString', 'MemberwiseClone', 'Finalize', 'ReferenceEquals', 'Lucide', 'BuiltInIcons']);

const GENERATED_HEADER = [
  '// <auto-generated>',
  '// 由 tools/icon-gen/generate.mjs 生成，请勿手改；数据来源与许可见 tools/icon-gen/NOTICE.md。',
  '// </auto-generated>',
  '#nullable enable',
  '',
];

const { values } = parseArgs({
  options: {
    source: {
      type: 'string',
      default: resolve(repoRoot, '../../IdeaProjects/vue-tsx-pro/node_modules/.pnpm/@lucide+icons@1.59.0/node_modules/@lucide/icons'),
    },
    check: { type: 'boolean', default: false },
  },
});
const iconsDir = resolve(values.source, 'dist/esm/icons');
if (!existsSync(iconsDir)) {
  console.error(`找不到 ${iconsDir}；用 --source 指定 @lucide/icons 包目录`);
  process.exit(2);
}

const compareOrdinal = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** 属性值转义成 XML 属性文本 */
const escapeXml = (s) => s.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

/** 元素节点 → 标记，如 `<path d="M5 12h14"/>`；属性保持数据里的顺序，丢弃 key */
function elementMarkup([tag, attributes]) {
  const attrs = Object.entries(attributes)
    .filter(([name]) => name !== 'key')
    .map(([name, value]) => ` ${name}="${escapeXml(String(value))}"`)
    .join('');
  return `<${tag}${attrs}/>`;
}

/** 标记 → C# 普通字符串字面量 */
const csharpString = (s) => '"' + s.replace(/["\\]/g, '\\$&') + '"';

/** 图标名 → C# 属性名：连字符切词转 PascalCase（`arrow-up-right` → ArrowUpRight）；数字开头或与保留名冲突时加 Icon 前缀/后缀 */
function propertyName(name) {
  const pascal = name
    .split('-')
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
  if (/^\d/.test(pascal)) return 'Icon' + pascal;
  return RESERVED_MEMBERS.has(pascal) ? pascal + 'Icon' : pascal;
}

async function loadIcons() {
  const icons = [];
  for (const file of readdirSync(iconsDir).filter((f) => f.endsWith('.mjs') && f !== 'index.mjs')) {
    const { default: icon } = await import(pathToFileURL(resolve(iconsDir, file)).href);
    if (icon.size !== 24) throw new Error(`${icon.name}：坐标系不是 24×24，需要 IconData 带 ViewBox`);
    icons.push({ name: icon.name, body: icon.node.map(elementMarkup).join('') });
  }
  icons.sort((a, b) => compareOrdinal(a.name, b.name));
  const seen = new Map();
  for (const icon of icons) {
    icon.property = propertyName(icon.name);
    if (seen.has(icon.property)) throw new Error(`属性名冲突：${seen.get(icon.property)} 与 ${icon.name} 都是 ${icon.property}`);
    seen.set(icon.property, icon.name);
  }
  return icons;
}

/** 生成一个静态类的源码 */
function render(namespace, className, summary, icons) {
  // IconData 在 Rune.UI；BuiltInIcons 本身就在这个命名空间里，不需要 using
  const usings = namespace === 'Rune.UI' ? [] : ['using Rune.UI;', ''];
  const lines = [...GENERATED_HEADER, ...usings, `namespace ${namespace};`, '', '/// <summary>', `/// ${summary}`, '/// </summary>', `public static partial class ${className}`, '{'];
  for (const icon of icons) {
    lines.push(`    /// <summary>Lucide 图标 <c>${icon.name}</c>。</summary>`);
    lines.push(`    public static IconData ${icon.property} => field ??= new(${csharpString(icon.name)}, ${csharpString(icon.body)});`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const all = await loadIcons();
const byName = new Map(all.map((i) => [i.name, i]));
const missing = BUILT_IN.filter((n) => !byName.has(n));
if (missing.length) throw new Error(`内置清单里的图标在数据里不存在：${missing.join(', ')}`);

const outputs = [
  [lucidePath, render('Rune.Icons', 'Lucide', `Lucide 图标全集（${all.length} 个），每个图标一个按需创建的静态属性；用法 <c>&lt;Icon Data="Lucide.Plus" /&gt;</c>。`, all)],
  [
    builtInPath,
    render(
      'Rune.UI',
      'BuiltInIcons',
      `组件库自己要用的 Lucide 图标（${BUILT_IN.length} 个）；需要更多图标时引用 Rune.Icons 包。`,
      BUILT_IN.map((n) => byName.get(n)).sort((a, b) => compareOrdinal(a.name, b.name)),
    ),
  ],
];

let stale = false;
for (const [path, content] of outputs) {
  if (values.check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replaceAll('\r\n', '\n') : null;
    if (current !== content) {
      console.error(`已过期：${path}`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`已写入 ${path}`);
  }
}
if (stale) process.exit(1);
console.log(values.check ? '生成文件均为最新' : `共 ${all.length} 个图标，内置 ${BUILT_IN.length} 个`);
