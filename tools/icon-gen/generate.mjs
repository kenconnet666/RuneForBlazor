#!/usr/bin/env node
// 从 Lucide 官方的 SVG 文件（npm 包 lucide-static）生成 C# 的图标数据：全集（Rune.Icons 包）与组件库内置的小集合（Rune.UI）。
//
// 用法：node tools/icon-gen/generate.mjs [--source <lucide-static 的 package 目录>] [--check]
//   --source  已解压的 lucide-static 包目录；不写时用 npm pack 下载 LUCIDE_VERSION 到临时目录
//   --check   只比较不写入；任一生成文件与现有内容不一致时以非零状态退出（CI 用）
//
// 输出：
//   src/Rune.Icons/Lucide.g.cs                     全集，Rune.Icons.Lucide.Plus
//   src/Rune.Icons/LICENSE-lucide.txt              Lucide 的许可（随包分发）
//   src/Rune.UI/Components/Icon/BuiltInIcons.g.cs  组件库自己要用的图标（见 BUILT_IN），Rune.UI.BuiltInIcons.Plus
//
// 数据：icons/<名字>.svg 是每个图标的 SVG，取 <svg> 里面的元素作为 IconData.Body（外层的 svg 属性由 Icon 组件统一给）；
// tags.json 的键是现行的图标名，值是搜索关键词（写进文档注释，IDE 里能搜到）。不在 tags.json 里的 SVG 是改名前的旧名，
// 内容与某个现行图标相同，生成为标了 [Obsolete] 的转发属性，照着 Lucide 旧文档写的代码仍能编译并提示新名字。
// 每个图标一个“按需创建”的静态属性（field ??=），避免类型初始化时一次建出全部对象，也便于 WebAssembly 发布时裁剪未用到的成员。
//
// 依赖：node 内置模块；下载时用 npm 与 tar（Node 与 Windows / Linux / macOS 都自带）。数据来源与许可见 NOTICE.md。

import { execFileSync, execSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

/** 使用的 Lucide 版本；升级时改这里并重新生成 */
const LUCIDE_VERSION = '1.68.0';

const repoRoot = resolve(import.meta.dirname, '../..');
const lucidePath = resolve(repoRoot, 'src/Rune.Icons/Lucide.g.cs');
const licensePath = resolve(repoRoot, 'src/Rune.Icons/LICENSE-lucide.txt');
const builtInPath = resolve(repoRoot, 'src/Rune.UI/Components/Icon/BuiltInIcons.g.cs');

/** 组件库内置的图标：组件自己要用的，新增组件需要图标时往这里加一项再重新生成 */
const BUILT_IN = [
  'x',
  'check',
  'chevron-down',
  'chevron-up',
  'chevron-left',
  'chevron-right',
  'info',
  'circle-check',
  'triangle-exclamation-point',
  'circle-exclamation-point',
  'minus',
  'plus',
  'search',
  'loader-circle',
  'external-link',
  'copy',
];

/** 文档注释里最多列几个关键词 */
const MAX_TAGS = 8;

/** 属性名不能取的名字：object 的成员与所在类自身（C# 关键字都是小写，PascalCase 后不会冲突） */
const RESERVED_MEMBERS = new Set(['Equals', 'GetHashCode', 'GetType', 'ToString', 'MemberwiseClone', 'Finalize', 'ReferenceEquals', 'Lucide', 'BuiltInIcons']);

const GENERATED_HEADER = [
  '// <auto-generated>',
  `// 由 tools/icon-gen/generate.mjs 从 lucide-static ${LUCIDE_VERSION} 生成，请勿手改；数据来源与许可见 tools/icon-gen/NOTICE.md。`,
  '// </auto-generated>',
  '#nullable enable',
  '',
];

const { values } = parseArgs({
  options: {
    source: { type: 'string' },
    check: { type: 'boolean', default: false },
  },
});

/** 取得 lucide-static 的 package 目录：指定的目录，或下载到临时目录（返回清理函数） */
function obtainPackage() {
  if (values.source) return { dir: resolve(values.source), cleanup: () => {} };
  const temp = mkdtempSync(join(tmpdir(), 'rune-lucide-'));
  // Windows 上 npm 是 npm.cmd，要经 shell 执行；命令里只有固定的版本号
  execSync(`npm pack lucide-static@${LUCIDE_VERSION} --silent`, { cwd: temp, stdio: ['ignore', 'ignore', 'inherit'] });
  execFileSync('tar', ['-xzf', `lucide-static-${LUCIDE_VERSION}.tgz`], { cwd: temp, stdio: 'inherit' });
  return { dir: join(temp, 'package'), cleanup: () => rmSync(temp, { recursive: true, force: true }) };
}

/** SVG 文件 → <svg> 里面的元素，去掉缩进与换行、自闭合写成 <path …/> */
function svgBody(name, text) {
  const open = /<svg\b([^>]*)>/.exec(text);
  const close = text.lastIndexOf('</svg>');
  if (!open || close < 0) throw new Error(`${name}.svg：不是 svg`);
  if (!/viewBox="0 0 24 24"/.test(open[1])) throw new Error(`${name}.svg：坐标系不是 24×24，需要 IconData 带 ViewBox`);
  const body = text
    .slice(open.index + open[0].length, close)
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
  if (/<(?!\/?(?:path|circle|rect|line|polyline|polygon|ellipse)\b)/.test(body)) throw new Error(`${name}.svg：含有不认识的元素`);
  return body;
}

function loadIcons(dir) {
  const tags = JSON.parse(readFileSync(join(dir, 'tags.json'), 'utf8'));
  const svgs = new Map(
    readdirSync(join(dir, 'icons'))
      .filter((f) => f.endsWith('.svg'))
      .map((f) => {
        const name = f.slice(0, -4);
        return [name, svgBody(name, readFileSync(join(dir, 'icons', f), 'utf8'))];
      }),
  );

  const icons = Object.keys(tags).map((name) => {
    if (!svgs.has(name)) throw new Error(`tags.json 里的 ${name} 没有对应的 SVG`);
    return { name, body: svgs.get(name), tags: tags[name], property: propertyName(name) };
  });
  const seen = new Map();
  for (const icon of icons) {
    if (seen.has(icon.property)) throw new Error(`属性名冲突：${seen.get(icon.property)} 与 ${icon.name} 都是 ${icon.property}`);
    seen.set(icon.property, icon.name);
  }

  // 旧名转成属性名后可能与现行图标相同（arrow-down-01 与 arrow-down-0-1 都是 ArrowDown01），这样的旧名不需要转发
  const byBody = new Map(icons.map((i) => [i.body, i]));
  const aliases = [...svgs]
    .filter(([name]) => !(name in tags))
    .map(([name, body]) => {
      const target = byBody.get(body);
      if (!target) throw new Error(`${name}.svg 不在 tags.json 里，也不是任何现行图标的旧名`);
      return { name, target, property: propertyName(name) };
    })
    .filter((alias) => !seen.has(alias.property));
  icons.sort((a, b) => compareOrdinal(a.name, b.name));
  aliases.sort((a, b) => compareOrdinal(a.name, b.name));
  return { icons, aliases, license: readFileSync(join(dir, 'LICENSE'), 'utf8') };
}

/** 图标名 → PascalCase 属性名：arrow-up-01 → ArrowUp01；以数字开头的前面加下划线 */
function propertyName(name) {
  let property = name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
  if (/^[0-9]/.test(property)) property = `_${property}`;
  if (RESERVED_MEMBERS.has(property)) property += 'Icon';
  return property;
}

function compareOrdinal(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function csharpString(text) {
  return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function escapeXml(text) {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function summary(icon) {
  const tags = icon.tags.slice(0, MAX_TAGS).map(escapeXml).join('、');
  return `    /// <summary>Lucide 图标 <c>${icon.name}</c>${tags ? `（${tags}）` : ''}。</summary>`;
}

/** 生成一个静态类的源码 */
function render(namespace, className, classSummary, icons, aliases = []) {
  // IconData 在 Rune.UI；BuiltInIcons 本身就在这个命名空间里，不需要 using
  const usings = namespace === 'Rune.UI' ? [] : ['using Rune.UI;', ''];
  const lines = [...GENERATED_HEADER, ...usings, `namespace ${namespace};`, '', '/// <summary>', `/// ${classSummary}`, '/// </summary>', `public static partial class ${className}`, '{'];
  for (const icon of icons) {
    lines.push(summary(icon));
    lines.push(`    public static IconData ${icon.property} => field ??= new(${csharpString(icon.name)}, ${csharpString(icon.body)});`);
  }
  if (aliases.length) lines.push('', '    // ---- Lucide 改名前的旧名：转发到现行图标 ----', '');
  for (const alias of aliases) {
    lines.push(`    /// <summary>Lucide 旧名 <c>${alias.name}</c>，现名 <see cref="${alias.target.property}"/>。</summary>`);
    lines.push(`    [System.Obsolete("Lucide 已改名为 ${alias.target.name}，请用 ${className}.${alias.target.property}")]`);
    lines.push(`    public static IconData ${alias.property} => ${alias.target.property};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const source = obtainPackage();
let loaded;
try {
  loaded = loadIcons(source.dir);
} finally {
  source.cleanup();
}
const { icons, aliases, license } = loaded;
const byName = new Map(icons.map((i) => [i.name, i]));
const missing = BUILT_IN.filter((n) => !byName.has(n));
if (missing.length) throw new Error(`内置清单里的图标不是现行图标名：${missing.join(', ')}`);

const outputs = [
  [
    lucidePath,
    render(
      'Rune.Icons',
      'Lucide',
      `Lucide 图标全集（${icons.length} 个，另有 ${aliases.length} 个旧名），每个图标一个按需创建的静态属性；用法 <c>&lt;Icon Data="Lucide.Plus" /&gt;</c>。`,
      icons,
      aliases,
    ),
  ],
  [licensePath, license],
  [
    builtInPath,
    render(
      'Rune.UI',
      'BuiltInIcons',
      `组件库自己要用的 Lucide 图标（${BUILT_IN.length} 个）；需要更多图标时引用 Rune.Icons 包。`,
      BUILT_IN.map((n) => byName.get(n)).sort((a, b) => compareOrdinal(a.name, b.name)),
    ),
  ],
];

let stale = false;
for (const [path, content] of outputs) {
  if (values.check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8').replaceAll('\r\n', '\n') : null;
    if (current !== content.replaceAll('\r\n', '\n')) {
      console.error(`已过期：${path}`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`已写入 ${path}`);
  }
}
if (stale) process.exit(1);
console.log(values.check ? '生成文件均为最新' : `Lucide ${LUCIDE_VERSION}：${icons.length} 个图标、${aliases.length} 个旧名，内置 ${BUILT_IN.length} 个`);
